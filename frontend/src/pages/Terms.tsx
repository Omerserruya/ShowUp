function BlockView({ block }: { block: Block }) {
  if ('p' in block) {
    return <Typography paragraph>{block.p}</Typography>;
  }
  return (
    <Typography component="div">
      <ul>
        {block.ul.map((item, i) => (
          <li key={i}>{item}</li>
        ))}
      </ul>
    </Typography>
  );
}

